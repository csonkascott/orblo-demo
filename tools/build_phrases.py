"""Builds assets/phrases.js from Orblo's phrase list (data/avoid-phrases.json in the app repo).

Usage: python3 tools/build_phrases.py path/to/avoid-phrases.json
"""
import json
import sys

src = json.load(open(sys.argv[1], encoding="utf-8"))
out = []
for cat in src["categories"]:
    for p in cat["phrases"]:
        out.append({"p": p["phrase"], "re": p["pattern"], "alt": p.get("alt", "cut"), "cat": cat["title"]})
head = "/* Generated by tools/build_phrases.py from Orblo's phrase list (version %s, %s). Do not edit by hand. */\n" % (src["version"], src["updated"])
open("assets/phrases.js", "w", encoding="utf-8").write(head + "window.OB_PHRASES = " + json.dumps(out, ensure_ascii=False) + ";\n")
print(len(out), "phrases")
